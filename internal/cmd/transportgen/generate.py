#!/usr/bin/env python3
"""Generate the shared protobuf transport and static SDK conversions.

Run from any directory. GO may select a built isolate toolchain; protoc must be
on PATH. protoc-gen-go is built from this module's pinned protobuf dependency.
The temporary descriptor set supplies all imported protos from those same pins.
"""
import json
import os
import pathlib
import subprocess
import tempfile

os.chdir(pathlib.Path(__file__).resolve().parents[3])
go = os.environ.get("GO", "go")
workspace = tempfile.TemporaryDirectory(prefix="tgo-transport-")
temporary = pathlib.Path(workspace.name)
types_path = temporary / "types.json"
descriptors_path = temporary / "dependencies.pb"
subprocess.run([go, "run", "-tags=transportgen", "./internal/cmd/transportgen",
                "-types", str(types_path), "-descriptors", str(descriptors_path)], check=True)
x=json.loads(types_path.read_text());types=x['types'];roots=x['roots']
msg={k:v['Name'] for k,v in types.items() if v['Kind']=='struct' and not v['Proto'] and v['Name']!='Time'}
imports={'google/protobuf/timestamp.proto'}
for v in types.values():
 if v['Proto']:imports.add(v['File'])
imports.add('temporal/api/common/v1/message.proto');imports.add('temporal/api/failure/v1/message.proto')

def ptype(k,field=''):
 d=types[k];kind=d['Kind']
 if kind=='ptr':return ptype(d['Elem'],field)
 if d['Proto']:return d['Proto']
 if d['Name']=='Time' and d['Pkg']=='time':return 'google.protobuf.Timestamp'
 if kind=='struct':return msg[k]
 if kind=='interface':return 'VersioningOverride'
 if kind=='map':return 'map<'+ptype(d['Key'])+', '+ptype(d['Elem'])+'>'
 if kind=='slice':
  if types[d['Elem']]['Kind']=='uint8':
   return 'bytes'
  return 'repeated '+ptype(d['Elem'])
 if kind=='string':return 'string'
 if kind=='bool':return 'bool'
 if kind.startswith('uint'):return 'uint64'
 if kind.startswith('int'):return 'sint64'
 if kind.startswith('float'):return 'double'
 raise ValueError((k,d))
schema=['// Code generated by internal/cmd/transportgen; DO NOT EDIT.','syntax = "proto3";','package tgo.transport;','option go_package = "github.com/mfateev/sdk-go-poc/internal/transportpb";']
schema+=['import "'+i+'";' for i in sorted(imports)]
for k,name in sorted(msg.items(),key=lambda v:v[1]):
 schema.append('message '+name+' {')
 fields=[]
 for f in types[k]['Fields'] or []:
  fields.extend(types[f['Type']]['Fields'] if f['Embedded'] else [f])
 for i,f in enumerate(fields,1):schema.append('  '+ptype(f['Type'],f['Name'])+' '+f['Name']+' = '+str(i)+';')
 schema.append('}')
schema+=['message PayloadFields { map<string, temporal.api.common.v1.Payload> Fields = 1; }','message VersioningOverride { string Kind = 1; string DeploymentName = 2; string BuildID = 3; }']
pathlib.Path('internal/transportpb').mkdir(exist_ok=True)
pathlib.Path('internal/transportpb/transport.proto').write_text('\n'.join(schema)+'\n')
# Static conversion code keeps SDK API aliases in their owning package; generic
# setters infer internal SDK enum/struct types without importing internal packages.
out=['//go:build !transportgen','','// Code generated by internal/cmd/transportgen; DO NOT EDIT.','package workflow','import (','"encoding/binary"','"fmt"','','wirepb "github.com/mfateev/sdk-go-poc/internal/transportpb"','"google.golang.org/protobuf/proto"','"google.golang.org/protobuf/types/known/timestamppb"','"go.temporal.io/sdk/client"','commonpb "go.temporal.io/api/common/v1"','failurepb "go.temporal.io/api/failure/v1"',')', '''type wireInteger interface {~int|~int8|~int16|~int32|~int64|~uint|~uint8|~uint16|~uint32|~uint64}
func setWireInteger[T wireInteger,V wireInteger](dst *T,v V)error{
 n:=T(v);if V(n)!=v || (n<0)!=(v<0){return fmt.Errorf("transport integer overflow")};*dst=n;return nil
}
func setWireFloat[T ~float32|~float64](dst *T,v float64){*dst=T(v)}
func newWireValue[T any](dst **T){*dst=new(T)}
func makeWireSlice[T any](dst *[]T,n int){*dst=make([]T,n)}
func makeWireMap[M ~map[K]V,K comparable,V any](dst *M,n int){*dst=make(M,n)}
func wireMapValue[K comparable,V any](m map[K]V) V {var v V;return v}
func wireVersioning(value client.VersioningOverride) (*wirepb.VersioningOverride,error) {
 if value==nil{return nil,nil}
 switch v:=value.(type){
 case *client.PinnedVersioningOverride:if v==nil{return nil,nil};return &wirepb.VersioningOverride{Kind:"pinned",DeploymentName:v.Version.DeploymentName,BuildID:v.Version.BuildID},nil
 case *client.AutoUpgradeVersioningOverride:if v==nil{return nil,nil};return &wirepb.VersioningOverride{Kind:"auto"},nil
 case *client.OneTimeVersioningOverride:if v==nil{return nil,nil};return &wirepb.VersioningOverride{Kind:"once",DeploymentName:v.TargetVersion.DeploymentName,BuildID:v.TargetVersion.BuildID},nil
 default:return nil,fmt.Errorf("unsupported versioning override %T",value)
 }
}
func domainVersioning(value *wirepb.VersioningOverride)(client.VersioningOverride,error) {
 if value==nil{return nil,nil}
 switch value.Kind{case "pinned":v:=&client.PinnedVersioningOverride{};v.Version.DeploymentName=value.DeploymentName;v.Version.BuildID=value.BuildID;return v,nil;case "auto":return &client.AutoUpgradeVersioningOverride{},nil;case "once":v:=&client.OneTimeVersioningOverride{};v.TargetVersion.DeploymentName=value.DeploymentName;v.TargetVersion.BuildID=value.BuildID;return v,nil;default:return nil,fmt.Errorf("invalid versioning override %q",value.Kind)}

}
''']
counter=0

def emit(k,src,dst,to,field=''):
 global counter
 d=types[k];kind=d['Kind'];code=[]
 def add(s):code.append(s)
 def recurse(kk,ss,dd,ff=''):code.extend(emit(kk,ss,dd,to,ff))
 if kind=='ptr' and types[d['Elem']]['Proto']:
  add(dst+'='+src);return code
 if kind=='ptr':
  add('if '+src+'!=nil {')
  if to:
   elem=types[d['Elem']]
   if elem['Proto']:add(dst+'='+src)
   else:
    add(dst+'=new(wirepb.'+msg[d['Elem']]+')');recurse(d['Elem'],'(*'+src+')','(*'+dst+')',field)
  else:
   add('newWireValue(&'+dst+')');recurse(d['Elem'],'(*'+src+')','(*'+dst+')',field)
  add('}');return code
 if d['Proto']:add(dst+'='+src);return code
 if d['Pkg']=='time' and d['Name']=='Time':
  if to:add('if !'+src+'.IsZero(){'+dst+'=timestamppb.New('+src+')}')
  else:add('if '+src+'!=nil{'+dst+'='+src+'.AsTime()}')
  return code
 if kind=='struct':
  for f in d['Fields'] or []:
   t=types[f['Type']];ss=src if f['Embedded'] and not to else src+'.'+f['Name'];dd=dst if f['Embedded'] and to else dst+'.'+f['Name']
   nested=not f['Embedded'] and t['Kind']=='struct' and not t['Proto'] and t['Name']!='Time'
   if nested:add(dd+'=new(wirepb.'+msg[f['Type']]+')' if to else 'if '+ss+'!=nil{')
   recurse(f['Type'],ss,dd,f['Name'])
   if nested and not to:add('}')
  return code
 if kind=='interface':
  if to:add('{var err error;'+dst+',err=wireVersioning('+src+');if err!=nil{return nil,err}}')
  else:add('{var err error;'+dst+',err=domainVersioning('+src+');if err!=nil{return err}}')
  return code
 if kind=='slice' and types[d['Elem']]['Kind']=='uint8':
  add(dst+'='+src)
  return code
 if kind=='slice':
  counter+=1;i='i'+str(counter);add('if '+src+'!=nil{makeWireSlice(&'+dst+',len('+src+'));for '+i+':=range '+src+'{')
  elem=types[d['Elem']];nested=elem['Kind']=='struct' and not elem['Proto'] and elem['Name']!='Time'
  if nested:add(dst+'['+i+']=new(wirepb.'+msg[d['Elem']]+')' if to else 'if '+src+'['+i+']!=nil{')
  recurse(d['Elem'],src+'['+i+']',dst+'['+i+']')
  if nested and not to:add('}')
  add('}}');return code
 if kind=='map':
  counter+=1;i='key'+str(counter);v='value'+str(counter);z='mapped'+str(counter)
  add('if '+src+'!=nil{makeWireMap(&'+dst+',len('+src+'));for '+i+','+v+':=range '+src+'{');add(z+':=wireMapValue('+dst+')');recurse(d['Elem'],v,z);add(dst+'['+i+']='+z);add('}}');return code
 if kind.startswith('int') or kind.startswith('uint'):
  if to:add(dst+'='+('uint64' if kind.startswith('uint') else 'int64')+'('+src+')')
  else:add('if err:=setWireInteger(&'+dst+','+src+');err!=nil{return err}')
  return code
 if kind.startswith('float'):
  add(dst+'=float64('+src+')' if to else 'setWireFloat(&'+dst+','+src+')');return code
 add(dst+'='+src);return code
for k in roots:
 name=msg[k]
 out.append('func encodeWire'+name+'(in *'+name+')(*wirepb.'+name+',error){ out:=new(wirepb.'+name+')')
 out+=emit(k,'in','out',True);out.append('return out,nil }')
 out.append('func decodeWire'+name+'(in *wirepb.'+name+',out *'+name+')error{')
 codes=emit(k,'in','out',False)
 out+=codes;out.append('return nil }')
out+=['''// MarshalTransport encodes SDK envelopes independently of application data converters.
func MarshalTransport(value any)([]byte,error){
 switch v:=value.(type){
 case int:return binary.LittleEndian.AppendUint64(nil,uint64(v)),nil
 case uint64:return binary.LittleEndian.AppendUint64(nil,v),nil
 case Version:return binary.LittleEndian.AppendUint64(nil,uint64(v)),nil
 case bool:if v{return []byte{1},nil};return []byte{0},nil
 case map[string]*commonpb.Payload:return proto.MarshalOptions{Deterministic:true}.Marshal(&wirepb.PayloadFields{Fields:v})
''']
for k in roots:
 name=msg[k];out+=['case '+name+': p,err:=encodeWire'+name+'(&v);if err!=nil{return nil,err};return proto.MarshalOptions{Deterministic:true}.Marshal(p)','case *'+name+': if v==nil{return nil,fmt.Errorf("nil transport '+name+'")};p,err:=encodeWire'+name+'(v);if err!=nil{return nil,err};return proto.MarshalOptions{Deterministic:true}.Marshal(p)']
out+=['default:return nil,fmt.Errorf("unsupported transport value %T",value)','}}','''func UnmarshalTransport(data []byte,value any)error {
 switch v:=value.(type){
 case *uint64:if v==nil{return fmt.Errorf("nil transport destination")};if len(data)!=8{return fmt.Errorf("invalid transport integer")};*v=binary.LittleEndian.Uint64(data);return nil
 case *Version:if v==nil{return fmt.Errorf("nil transport destination")};if len(data)!=8{return fmt.Errorf("invalid transport version")};*v=Version(binary.LittleEndian.Uint64(data));return nil
 case *bool:if v==nil{return fmt.Errorf("nil transport destination")};if len(data)!=1||data[0]>1{return fmt.Errorf("invalid transport boolean")};*v=data[0]==1;return nil
 case *map[string]*commonpb.Payload:if v==nil{return fmt.Errorf("nil transport destination")};p:=new(wirepb.PayloadFields);if err:=proto.Unmarshal(data,p);err!=nil{return err};*v=p.Fields;return nil
''']
for k in roots:
 name=msg[k];out+=['case *'+name+':if v==nil{return fmt.Errorf("nil transport destination")};p:=new(wirepb.'+name+');if err:=proto.Unmarshal(data,p);err!=nil{return err};*v='+name+'{};return decodeWire'+name+'(p,v)']
out+=['default:return fmt.Errorf("unsupported transport destination %T",value)','}}']
text='\n'.join(out)+'\n'
if text.count('failurepb.')==0:text=text.replace('failurepb \"go.temporal.io/api/failure/v1\"\n','')
if text.count('commonpb.')==0:text=text.replace('commonpb \"go.temporal.io/api/common/v1\"\n','')
pathlib.Path('workflow/transport_generated.go').write_text(text)

plugin = temporary / "protoc-gen-go"
subprocess.run([go, "build", "-o", str(plugin), "google.golang.org/protobuf/cmd/protoc-gen-go"], check=True)
subprocess.run(["protoc", "-I", ".", "--descriptor_set_in=" + str(descriptors_path),
                "--plugin=protoc-gen-go=" + str(plugin), "--go_out=.",
                "--go_opt=module=github.com/mfateev/sdk-go-poc",
                "internal/transportpb/transport.proto"], check=True)
subprocess.run([go, "fmt", "./workflow", "./internal/transportpb"], check=True)
workspace.cleanup()
